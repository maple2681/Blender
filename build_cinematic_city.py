def steam_sites(specs, rng):
    """Where the steam comes from: roof vents on the nearest visible roofs, and street manholes.

    specs arrives sorted by distance, so walking it in order puts the plumes on the rooftops
    the camera is actually looking at rather than scattering them across the whole city.
    """
    roof, street = [], []
    for spec in specs:
        if not spec.get("clutter") or not spec.get("roofs") or spec["dist"] > 300.0:
            continue
        rect, zdeck, ztop = spec["roofs"][-1]
        x0, x1, y0, y1 = rect
        if (x1 - x0) * (y1 - y0) < 55.0:
            continue
        h = rng.uniform(11.0, 20.0)
        r = rng.uniform(2.6, 4.6)
        for _ in range(4):                       # try a few spots on this roof
            x = rng.uniform(x0 + r, max(x0 + r, x1 - r))
            y = rng.uniform(y0 + r, max(y0 + r, y1 - r))
            if visible_box(x - r, x + r, y - r, y + r, zdeck, zdeck + h, margin=0.04):
                roof.append((x, y, zdeck, h, r, 1.0))
                break
        if len(roof) >= P["steam_plumes"]:
            break
    half = P["avenue_road"] * 0.5
    y = P["cross_streets"][0] + 30.0
    while y < 380.0:
        if rng.random() < 0.34:
            x = P["avenue_x"] + rng.uniform(-half * 0.7, half * 0.7)
            r = rng.uniform(2.2, 3.6)
            if visible_box(x - r, x + r, y - r, y + r, 0.0, 11.0, margin=0.04):
                street.append((x, y, 0.05, rng.uniform(8.0, 14.0), r, 0.7))
        y += 26.0
    n = P["steam_plumes"]
    out = roof[:max(0, n - min(len(street), n // 3))] + street[:max(0, n // 3)]
    log("steam sites: %d on roofs, %d in the street" % (len(roof), len(street)))
    return out[:n]


def build_steam(specs, c, rng):
    """Plumes of vapour: a drifting, ray-marched volume box over each vent."""
    if not (P["steam"] and P["use_volumes"]):
        return 0
    sites = steam_sites(specs, rng)
    n = 0
    for i, (x, y, z, h, r, strength) in enumerate(sites):
        if not visible_box(x - r, x + r, y - r, y + r, z, z + h, margin=0.10):
            continue
        bm = bmesh.new()
        bm_box(bm, (0.0, 0.0, h * 0.5), (2.2 * r, 2.2 * r, h))
        mat = mat_get("steam%d" % (i % 3), mat_steam, "Steam%d" % (i % 3),
                      P["steam_density"] * strength * rng.uniform(0.75, 1.3))
        ob = bm_to_obj("Steam%02d" % i, bm, c, [mat])
        ob.location = (x, y, z)
        setp(ob, "display_type", 'WIRE')
        setp(ob, "visible_shadow", True)
        # the plume leans over and grows as it drifts away on the wind
        ob.scale = (1.0, 1.0, 1.0)
        ob.keyframe_insert("scale", frame=P["frame_start"])
        ob.scale = (1.22, 1.22, 1.12)
        ob.keyframe_insert("scale", frame=P["frame_end"])
        ease_keys(ob, P["frame_start"], P["frame_end"], 0.8)
        n += 1
    log("steam: %d plumes" % n)
    return n


