def mslot(bm, idx, fn, *a, **kw):
    """Run a bmesh primitive and tag every face it made with a material slot."""
    n0 = len(bm.faces)
    r = fn(bm, *a, **kw)
    bm.faces.ensure_lookup_table()
    for f in bm.faces[n0:]:
        f.material_index = idx
    return r


def quad(bm, p0, p1, p2, p3):
    vs = [bm.verts.new(p) for p in (p0, p1, p2, p3)]
    bm.faces.new(vs)
    return vs


def slab(bm, x0, x1, y0, y1, z0, z1):
    return bm_box(bm, (0.5 * (x0 + x1), 0.5 * (y0 + y1), 0.5 * (z0 + z1)),
                  (abs(x1 - x0), abs(y1 - y0), abs(z1 - z0)))


SIDES = (('x', -1), ('x', 1), ('y', -1), ('y', 1))


def side_plane(rect, axis, sgn, inset=0.0):
    """Outer plane position and the in-plane span of one facade of a rectangular mass."""
    x0, x1, y0, y1 = rect
    if axis == 'x':
        p = (x1 - inset) if sgn > 0 else (x0 + inset)
        return p, (y0 + inset, y1 - inset)
    p = (y1 - inset) if sgn > 0 else (y0 + inset)
    return p, (x0 + inset, x1 - inset)


def face_box(bm, axis, sgn, plane, a0, a1, z0, z1, depth):
    """A box sitting on one facade: 'a' is the in-plane axis, depth is how far it stands proud."""
    if axis == 'x':
        x0, x1 = (plane, plane + depth * sgn)
        return slab(bm, min(x0, x1), max(x0, x1), a0, a1, z0, z1)
    y0, y1 = (plane, plane + depth * sgn)
    return slab(bm, a0, a1, min(y0, y1), max(y0, y1), z0, z1)


def face_quad(bm, axis, sgn, plane, a0, a1, z0, z1):
    if axis == 'x':
        pts = [(plane, a0, z0), (plane, a1, z0), (plane, a1, z1), (plane, a0, z1)]
    else:
        pts = [(a0, plane, z0), (a1, plane, z0), (a1, plane, z1), (a0, plane, z1)]
    if sgn < 0:
        pts = list(reversed(pts))
    return quad(bm, *pts)


def exposed_sides(spec, specs, gap=3.2):
    """Which of the four facades face open air rather than a neighbour's party wall."""
    out = {}
    for axis, sgn in SIDES:
        plane, (a0, a1) = side_plane((spec["x0"], spec["x1"], spec["y0"], spec["y1"]), axis, sgn)
        blocked = False
        for o in specs:
            if o is spec or o["h"] < spec["h"] * 0.45:
                continue
            if axis == 'x':
                near = (o["x0"] - plane) if sgn > 0 else (plane - o["x1"])
                span = (o["y0"], o["y1"])
            else:
                near = (o["y0"] - plane) if sgn > 0 else (plane - o["y1"])
                span = (o["x0"], o["x1"])
            if -0.5 <= near <= gap and span[1] > a0 + 1.5 and span[0] < a1 - 1.5:
                blocked = True
                break
        out[(axis, sgn)] = not blocked
    return out


def tiers(spec, rng):
    """Split a tall building into setback tiers: [(rect, z0, z1), ...]."""
    x0, x1, y0, y1 = spec["x0"], spec["x1"], spec["y0"], spec["y1"]
    h, style = spec["h"], spec["style"]
    if h < 46.0 or style == 'infill' or rng.random() < (0.25 if style == 'stone' else 0.65):
        return [((x0, x1, y0, y1), 0.0, h)]
    n = 2 if (h < 95.0 or rng.random() < 0.5) else 3
    out, z = [], 0.0
    rect = (x0, x1, y0, y1)
    for i in range(n):
        frac = rng.uniform(0.42, 0.62) if i == 0 else rng.uniform(0.45, 0.7)
        top = z + (h - z) * (frac if i < n - 1 else 1.0)
        out.append((rect, z, top))
        ins = rng.uniform(1.6, 4.2)
        nx0, nx1 = rect[0] + ins, rect[1] - ins
        ny0, ny1 = rect[2] + ins * rng.uniform(0.4, 1.3), rect[3] - ins * rng.uniform(0.4, 1.3)
        if nx1 - nx0 < 8.0 or ny1 - ny0 < 8.0:
            if out[-1][2] < h:
                out[-1] = (rect, z, h)
            break
        rect, z = (nx0, nx1, ny0, ny1), top
    if out[-1][2] < h - 0.5:
        out.append((rect, out[-1][2], h))
    return out


def facade_grid(width, style, rng):
    """Window columns across one facade: returns (n, pitch, window width)."""
    if style == 'glass':
        pitch = rng.uniform(1.42, 1.72)
    elif style == 'brick':
        pitch = rng.uniform(2.35, 3.15)
    elif style == 'stone':
        pitch = rng.uniform(2.6, 3.6)
    else:
        pitch = rng.uniform(2.8, 4.0)
    n = max(1, int(round(width / pitch)))
    pitch = width / n
    frac = {'glass': 0.88, 'brick': 0.52, 'stone': 0.56, 'infill': 0.46}[style]
    return n, pitch, pitch * frac * rng.uniform(0.94, 1.06)


def build_facade(bm, spec, rect, z0, z1, style, rng, exposed, reveal, fh):
    """Bands, piers and glazing on the four faces of one tier."""
    glass_slot = SLOT_GLASS
    nf = max(1, int(round((z1 - z0) / fh)))
    fh_a = (z1 - z0) / nf
    for axis, sgn in SIDES:
        plane, (a0, a1) = side_plane(rect, axis, sgn)
        width = a1 - a0
        if width < 3.0:
            continue
        if not exposed.get((axis, sgn), True):
            continue
        n, pitch, ww = facade_grid(width, style, rng)
        inner = plane - reveal * sgn                       # the recessed wall surface
        if style == 'glass':
            # continuous glazing with slab bands and slim mullions
            face_quad(bm, axis, sgn, inner + 0.012 * sgn, a0, a1, z0 + 0.05, z1 - 0.05)
            bm.faces.ensure_lookup_table()
            bm.faces[-1].material_index = glass_slot
            band_h = min(0.85, fh_a * 0.22)
            for i in range(nf + 1):
                z = z0 + i * fh_a
                mslot(bm, SLOT_TRIM, face_box, axis, sgn, inner, a0, a1,
                      z - band_h * 0.5, z + band_h * 0.5, reveal)
            for k in range(n + 1):
                a = a0 + k * pitch
                mslot(bm, SLOT_TRIM, face_box, axis, sgn, inner,
                      a - 0.045, a + 0.045, z0, z1, reveal * 0.92)
        else:
            sill = fh_a * rng.uniform(0.22, 0.30)
            wh = fh_a * rng.uniform(0.44, 0.56)
            for i in range(nf):
                zf = z0 + i * fh_a
                # spandrel band between this floor's window head and the next sill
                mslot(bm, SLOT_WALL, face_box, axis, sgn, inner, a0, a1,
                      zf + sill + wh, zf + fh_a + sill, reveal)
                for k in range(n):
                    a = a0 + (k + 0.5) * pitch
                    # pier between the windows
                    mslot(bm, SLOT_WALL, face_box, axis, sgn, inner,
                          a + ww * 0.5, a + pitch - ww * 0.5, zf + sill, zf + sill + wh, reveal)
                    # the glazing itself, set back in its reveal
                    face_quad(bm, axis, sgn, inner + 0.02 * sgn, a - ww * 0.5, a + ww * 0.5,
                              zf + sill + 0.02, zf + sill + wh - 0.02)
                    bm.faces.ensure_lookup_table()
                    bm.faces[-1].material_index = glass_slot
                    # stone sill under each opening
                    if style in ('brick', 'stone'):
                        mslot(bm, SLOT_TRIM, face_box, axis, sgn, inner,
                              a - ww * 0.5 - 0.10, a + ww * 0.5 + 0.10,
                              zf + sill - 0.10, zf + sill, reveal * 1.25)
                # the last pier, closing the run at the end of the wall
                mslot(bm, SLOT_WALL, face_box, axis, sgn, inner, a0, a0 + (pitch - ww) * 0.5,
                      zf + sill, zf + sill + wh, reveal)
            # base course / shopfront band at street level
            if z0 < 1.0:
                mslot(bm, SLOT_TRIM, face_box, axis, sgn, inner, a0, a1, 0.0, sill * 0.9, reveal * 1.4)


def build_roof(bm, rect, z, style, rng, parapet=True):
    """Roof deck, parapet wall and its stone coping."""
    x0, x1, y0, y1 = rect
    mslot(bm, SLOT_ROOF, slab, x0, x1, y0, y1, z - 0.22, z)
    if not parapet:
        return z
    ph = rng.uniform(0.85, 1.55)
    t = rng.uniform(0.28, 0.45)
    for axis, sgn in SIDES:
        plane, (a0, a1) = side_plane(rect, axis, sgn)
        mslot(bm, SLOT_WALL, face_box, axis, sgn, plane, a0, a1, z, z + ph, -t)
        mslot(bm, SLOT_TRIM, face_box, axis, sgn, plane + 0.05 * sgn, a0, a1,
              z + ph, z + ph + 0.09, -(t + 0.10))
    return z + ph


def build_building(spec, specs, c, rng):
    """One complete building: mass, facades, setbacks, roof decks."""
    style = spec["style"]
    bm = bmesh.new()
    reveal = 0.13 if style == 'glass' else rng.uniform(0.26, 0.42)
    fh = P["hero_floor"] if style == 'glass' else rng.uniform(3.15, 3.75)
    exposed = exposed_sides(spec, specs) if spec["detail"] else {k: True for k in SIDES}
    tt = tiers(spec, rng) if spec["detail"] else [((spec["x0"], spec["x1"], spec["y0"], spec["y1"]),
                                                   0.0, spec["h"])]
    roofs = []
    for rect, z0, z1 in tt:
        x0, x1, y0, y1 = rect
        if spec["detail"]:
            mslot(bm, SLOT_WALL, slab, x0 + reveal, x1 - reveal, y0 + reveal, y1 - reveal, z0, z1)
            build_facade(bm, spec, rect, z0, z1, style, rng, exposed, reveal, fh)
            top = build_roof(bm, (x0 + reveal, x1 - reveal, y0 + reveal, y1 - reveal), z1, style, rng)
        else:
            mslot(bm, SLOT_WALL, slab, x0, x1, y0, y1, 0.0, z1)
            mslot(bm, SLOT_ROOF, slab, x0 + 0.3, x1 - 0.3, y0 + 0.3, y1 - 0.3, z1, z1 + 0.35)
            top = z1 + 0.35
        roofs.append(((x0 + reveal, x1 - reveal, y0 + reveal, y1 - reveal), z1, top))
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-4)
    key = "far_" + style
    if spec["detail"]:
        pal = WALLS_WARM if spec.get("warm") else WALLS
        wall = MATS[rng.choice(pal[style])]        # no two neighbours are quite the same brick
    else:
        wall = mat_get(key, mat_facade_far, "Far" + style.title(), style)
    mats = [wall, MATS["window" if style != 'glass' else "curtain"], MATS["trim"], MATS["roofdeck"]]
    ob = bm_to_obj("Bld_%05d" % spec["seed"], bm, c, mats)
    spec["object"] = ob
    spec["roofs"] = roofs
    return ob


