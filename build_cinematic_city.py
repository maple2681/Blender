def free_spot(taken, x0, x1, y0, y1, w, d, rng, tries=14):
    """Rejection-sample a clear footprint on a roof."""
    if x1 - x0 < w + 0.6 or y1 - y0 < d + 0.6:
        return None
    for _ in range(tries):
        cx = rng.uniform(x0 + w / 2, x1 - w / 2)
        cy = rng.uniform(y0 + d / 2, y1 - d / 2)
        box = (cx - w / 2 - 0.35, cx + w / 2 + 0.35, cy - d / 2 - 0.35, cy + d / 2 + 0.35)
        if not any(overlaps(box, t) for t in taken):
            taken.append(box)
            return cx, cy
    return None


def dress_roof(spec, c, rng, protos):
    """Scatter the rooftop kit over one building's roof decks."""
    n_items = 0
    for idx, (rect, zdeck, ztop) in enumerate(spec.get("roofs", [])):
        x0, x1, y0, y1 = rect
        m = 1.5
        x0, x1, y0, y1 = x0 + m, x1 - m, y0 + m, y1 - m
        area = max(0.0, (x1 - x0) * (y1 - y0))
        if area < 26.0:
            continue
        taken = []
        z = zdeck
        big = area > 140.0
        # stair bulkhead
        if big and rng.random() < 0.72:
            p = free_spot(taken, x0, x1, y0, y1, 5.0, 4.0, rng)
            if p:
                place(protos["bulk"], c, (p[0], p[1], z), rng.uniform(0, 2 * pi) // (pi / 2) * (pi / 2),
                      rng.uniform(0.85, 1.25))
                n_items += 1
        # timber water tanks: the older and lower the building, the more likely
        if P["water_tanks"]:
            pw = 0.92 if spec["style"] in ('brick', 'stone') and spec["h"] < 105.0 else 0.50
            for _ in range(3 if area > 520.0 else (2 if area > 240.0 else 1)):
                if rng.random() < pw:
                    s = rng.uniform(0.82, 1.20)
                    p = free_spot(taken, x0, x1, y0, y1, 5.2 * s, 5.2 * s, rng)
                    if p:
                        place(protos["tank"], c, (p[0], p[1], z), rng.uniform(0, 2 * pi), s)
                        n_items += 1
        # air handlers and condensers
        for _ in range(rng.randint(2, 6 if big else 3)):
            k = rng.choice(["ac24", "ac24", "ac34", "ac16"])
            s = rng.uniform(0.85, 1.25)
            w = {"ac16": 1.6, "ac24": 2.4, "ac34": 3.4}[k] * s
            p = free_spot(taken, x0, x1, y0, y1, w, 2.2 * s, rng)
            if p:
                place(protos[k], c, (p[0], p[1], z), rng.choice([0.0, pi / 2, pi, -pi / 2])
                      + rng.uniform(-0.06, 0.06), s)
                n_items += 1
        if big and rng.random() < 0.55:
            p = free_spot(taken, x0, x1, y0, y1, 5.0, 1.6, rng)
            if p:
                place(protos["cond4"], c, (p[0], p[1], z), rng.choice([0.0, pi / 2]), 1.0)
                n_items += 1
        # ducts, pipes, skylights
        if big and rng.random() < 0.5:
            p = free_spot(taken, x0, x1, y0, y1, 7.5, 1.4, rng)
            if p:
                place(protos["duct"], c, (p[0], p[1], z), rng.choice([0.0, pi / 2]),
                      rng.uniform(0.8, 1.2))
                n_items += 1
        for _ in range(rng.randint(1, 3)):
            p = free_spot(taken, x0, x1, y0, y1, 2.4, 1.0, rng)
            if p:
                place(protos["pipes"], c, (p[0], p[1], z), rng.uniform(0, 2 * pi))
                n_items += 1
        if rng.random() < 0.4:
            p = free_spot(taken, x0, x1, y0, y1, 3.0, 2.2, rng)
            if p:
                place(protos["skylight"], c, (p[0], p[1], z), rng.choice([0.0, pi / 2]),
                      rng.uniform(0.8, 1.4))
                n_items += 1
        # vents: lots of them, they read as texture from the air
        for _ in range(rng.randint(4, 10 if big else 6)):
            k = "vent%d" % rng.randint(0, 2)
            p = free_spot(taken, x0, x1, y0, y1, 0.9, 0.9, rng)
            if p:
                place(protos[k], c, (p[0], p[1], z), rng.uniform(0, 2 * pi),
                      rng.uniform(0.8, 1.35))
                n_items += 1
        # masts and dishes, only on the topmost deck
        if idx == len(spec["roofs"]) - 1:
            if rng.random() < (0.45 if spec["h"] > 45.0 else 0.18):
                p = free_spot(taken, x0, x1, y0, y1, 1.6, 1.6, rng)
                if p:
                    place(protos["mast"], c, (p[0], p[1], z), rng.uniform(0, 2 * pi),
                          rng.uniform(0.7, 1.5))
                    n_items += 1
            for _ in range(rng.randint(0, 2)):
                p = free_spot(taken, x0, x1, y0, y1, 1.8, 1.8, rng)
                if p:
                    place(protos["dish"], c, (p[0], p[1], z), rng.uniform(0, 2 * pi),
                          rng.uniform(0.7, 1.25))
                    n_items += 1
    return n_items


