def mat_object_lamp(name, col, gain, channel=0):
    """A vehicle lamp whose brightness comes from the object's own colour, so one
    material can serve every instanced car and still be keyed per vehicle."""
    m, g, out = new_mat(name)
    oi = g.new('ShaderNodeObjectInfo', -900, 0)
    r, gg, b = g.separate(g.o(oi, "Color"), -700, 0)
    src = (r, gg, b)[channel]
    e = g.new('ShaderNodeEmission', 1100, 0)
    g.feed(g.i(e, "Color"), col)
    g.feed(g.i(e, "Strength"), g.math('MULTIPLY', src, gain, x=-400, y=0))
    set_emission_sampling(m, 'NONE')
    return finish(m, g, out, e)


