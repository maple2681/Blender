def street_corridors():
    """Half-widths of every street corridor: (axis, centre, half_road, half_total)."""
    av_r = P["avenue_road"] * 0.5
    av_t = av_r + P["sidewalk"]
    cr_r = P["cross_road"] * 0.5
    cr_t = cr_r + P["sidewalk"] * 0.72
    out = [('x', P["avenue_x"], av_r, av_t)]
    for s in (-1, 1):
        out.append(('x', P["avenue_x"] + s * P["side_avenue"], av_r * 0.82, av_t * 0.82))
    for y in P["cross_streets"]:
        out.append(('y', y, cr_r, cr_t))
    return out


def block_rects():
    """The land between the street corridors, as (x0, x1, y0, y1) blocks."""
    cor = street_corridors()
    xs = sorted([(c, t) for a, c, r, t in cor if a == 'x'])
    ys = sorted([(c, t) for a, c, r, t in cor if a == 'y'])
    y_lo = P["cross_streets"][0] - 150.0
    x_edges = [(-P["side_avenue"] - 150.0, xs[0][0] - xs[0][1])]
    for (c0, t0), (c1, t1) in zip(xs[:-1], xs[1:]):
        x_edges.append((c0 + t0, c1 - t1))
    x_edges.append((xs[-1][0] + xs[-1][1], P["side_avenue"] + 150.0))
    y_edges = [(y_lo, ys[0][0] - ys[0][1])]
    for (c0, t0), (c1, t1) in zip(ys[:-1], ys[1:]):
        y_edges.append((c0 + t0, c1 - t1))
    y_edges.append((ys[-1][0] + ys[-1][1], P["city_far"]))
    out = []
    for x0, x1 in x_edges:
        for y0, y1 in y_edges:
            if x1 - x0 > 14.0 and y1 - y0 > 14.0:
                out.append((x0, x1, y0, y1))
    return out


def split_rect(rect, rng, depth=0):
    """Recursively cut a block into building lots; returns [(x0, x1, y0, y1), ...]."""
    x0, x1, y0, y1 = rect
    w, d = x1 - x0, y1 - y0
    lo, hi = P["lot_min"], P["lot_max"]
    if depth > 7 or (w <= hi and d <= hi and (w <= lo * 1.9 or d <= lo * 1.9 or rng.random() < 0.3)):
        return [rect]
    along_x = w > d if abs(w - d) > 6.0 else rng.random() < 0.5
    span = w if along_x else d
    if span < lo * 2.0:
        return [rect]
    f = rng.uniform(0.34, 0.66)
    cut = lo + (span - 2 * lo) * f
    if along_x:
        a, b = (x0, x0 + cut, y0, y1), (x0 + cut, x1, y0, y1)
    else:
        a, b = (x0, x1, y0, y0 + cut), (x0, x1, y0 + cut, y1)
    return split_rect(a, rng, depth + 1) + split_rect(b, rng, depth + 1)


def cam_matrices(samples=5):
    """Camera world matrices sampled across the shot (for frustum culling)."""
    cam = OBJS.get("camera")
    if cam is None:
        return []
    fs, fe = P["frame_start"], P["frame_end"]
    mats, keep = [], SC.frame_current
    dg = bpy.context.evaluated_depsgraph_get() if bpy.context else None
    for i in range(samples):
        SC.frame_set(int(round(lerp(fs, fe, i / max(1, samples - 1)))))
        if dg is not None:
            dg.update()
        mats.append(cam.matrix_world.copy())
    SC.frame_set(keep)
    return mats


def visible_box(x0, x1, y0, y1, z0, z1, margin=0.16):
    """True if the box could touch the frame at any point in the shot."""
    from bpy_extras.object_utils import world_to_camera_view
    mats = OBJS.get("cam_mats") or []
    if not mats:
        return True
    cam = OBJS["camera"]
    corners = [Vector((x, y, z)) for x in (x0, x1) for y in (y0, y1) for z in (z0, z1)]
    keep = cam.matrix_world.copy()
    try:
        for M in mats:
            cam.matrix_world = M
            u0 = v0 = 1e9
            u1 = v1 = -1e9
            for p in corners:
                co = world_to_camera_view(SC, cam, p)
                if co.z <= 0.0:
                    return True                      # straddles the camera plane: keep it
                u0, u1 = min(u0, co.x), max(u1, co.x)
                v0, v1 = min(v0, co.y), max(v1, co.y)
            if u1 > -margin and u0 < 1.0 + margin and v1 > -margin and v0 < 1.0 + margin:
                return True
    finally:
        cam.matrix_world = keep
    return False


def cam_dist(x0, x1, y0, y1):
    c = Vector((0.5 * (x0 + x1), 0.5 * (y0 + y1), 0.0))
    cam = OBJS.get("camera")
    p = cam.matrix_world.translation if cam else Vector(P["cam_start"])
    return (c - Vector((p.x, p.y, 0.0))).length


def hero_rect():
    hx, hy = P["hero_x"], P["hero_y"]
    return (hx[0], hx[1], hy[0], hy[1])


def overlaps(a, b, pad=0.0):
    return not (a[1] <= b[0] + pad or a[0] >= b[1] - pad or a[3] <= b[2] + pad or a[2] >= b[3] - pad)


def pick_style(rng, h, dist):
    if h > 88.0:
        return 'glass' if rng.random() < 0.72 else 'stone'
    if h > 52.0:
        return rng.choice(['glass', 'stone', 'stone', 'brick'])
    if h > 30.0:
        return rng.choice(['brick', 'brick', 'stone', 'glass'])
    return rng.choice(['brick', 'infill', 'infill'])


def city_layout():
    """Every building in the city as a spec dict, culled to what the camera can see."""
    rng = random.Random(P["seed"] * 7 + 3)
    specs = []
    hero = hero_rect()
    for blk in block_rects():
        bx0, bx1, by0, by1 = blk
        for lot in split_rect(blk, rng):
            x0, x1, y0, y1 = lot
            g = rng.uniform(0.7, 2.3)                 # alley / light well between neighbours
            x0, x1, y0, y1 = x0 + g, x1 - g, y0 + g, y1 - g
            if x1 - x0 < 9.0 or y1 - y0 < 9.0:
                continue
            if P["hero"] and overlaps((x0, x1, y0, y1), hero, -2.0):
                continue
            dist = cam_dist(x0, x1, y0, y1)
            t = min(1.0, max(0.0, (dist - 90.0) / 420.0))
            lo, hi = P["h_near"], P["h_far"]
            h = rng.uniform(lerp(lo[0], hi[0], t), lerp(lo[1], hi[1], t))
            area = (x1 - x0) * (y1 - y0)
            h *= min(1.35, 0.55 + 0.45 * (area / 700.0) ** 0.5)   # big lots carry tall buildings
            if rng.random() < 0.07:
                h *= rng.uniform(1.4, 2.1)            # the occasional tower
            if 0.5 * (x0 + x1) < P["avenue_x"]:
                h = min(h * P["west_scale"], P["west_cap"])    # low, so the sun clears them
            else:
                h *= P["east_scale"]                           # tall, and lit down their west face
                deep = max(0.0, x0 - (P["avenue_x"] + P["avenue_road"] * 0.5 + P["sidewalk"]))
                h *= lerp(1.0, P["east_falloff"], min(1.0, deep / 140.0))
                if dist < 170.0:
                    h = min(h, P["near_cap"])                  # but not so tall they wall off the shot
            h = max(11.0, min(215.0, h))
            vis = visible_box(x0, x1, y0, y1, 0.0, h)
            if not vis and dist > 620.0:
                continue                              # too far to cast a shadow we would notice
            specs.append(dict(x0=x0, x1=x1, y0=y0, y1=y1, h=h, dist=dist, vis=vis,
                              warm=0.5 * (x0 + x1) > P["avenue_x"],
                              style=pick_style(rng, h, dist),
                              detail=vis and dist < P["detail_radius"],
                              clutter=vis and dist < P["clutter_radius"],
                              seed=rng.randrange(1 << 28)))
    specs.sort(key=lambda s: s["dist"])
    log("layout: %d buildings (%d in frame, %d detailed)"
        % (len(specs), sum(1 for s in specs if s["vis"]), sum(1 for s in specs if s["detail"])))
    return specs


