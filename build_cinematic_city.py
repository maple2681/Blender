def build_all(save_path=None):
    t0 = time.time()
    LOG.clear()
    prepare_scene()
    state = {}

    def step_city():
        state["specs"] = build_city()

    def step_street():
        c = coll("20_Street")
        build_ground(c)
        build_street_furniture(c, random.Random(P["seed"] + 21))
        build_trees(c, random.Random(P["seed"] + 22))

    def step_traffic():
        protos = build_vehicle_protos(coll("90_Prototypes"))
        build_traffic(coll("21_Traffic"), random.Random(P["seed"] + 31), protos)

    def step_signs():
        build_signage(state.get("specs", []), coll("30_Signage"),
                      random.Random(P["seed"] + 41))

    def step_air():
        c = coll("40_Atmosphere")
        build_atmosphere(c)
        build_steam(state.get("specs", []), c, random.Random(P["seed"] + 51))

    steps = [("render", setup_render), ("materials", build_materials), ("world", setup_world),
             ("camera", build_camera), ("city", step_city), ("street", step_street),
             ("traffic", step_traffic), ("signage", step_signs),
             ("sun", lambda: build_sun(coll("00_Camera"))), ("air", step_air),
             ("compositor", setup_compositor), ("edit scene", setup_edit_scene),
             ("viewport", setup_viewport)]
    for name, fn in steps:
        ts = time.time()
        try:
            fn()
            log("%-11s ok  %.1fs" % (name, time.time() - ts))
        except Exception as e:
            import traceback
            log("%-11s FAILED: %s" % (name, e))
            log(traceback.format_exc()[-2000:])
    try:
        if bpy.context.window is not None:
            bpy.context.window.scene = SC
    except Exception:
        pass
    SC.frame_set(P["frame_start"])
    try:
        remove_default_scene()
    except Exception as e:
        log("default scene", e)
    try:
        for wm in bpy.data.window_managers:
            for win in wm.windows:
                win.scene = SC
    except Exception as e:
        log("window scene", e)
    tris = sum(len(o.data.polygons) for o in SC.objects
               if o.type == 'MESH' and o.data is not None and not o.hide_render)
    log("%d objects, %d faces in the render" % (len(SC.objects), tris))
    if save_path:
        try:
            os.makedirs(os.path.dirname(save_path) or ".", exist_ok=True)
            bpy.ops.wm.save_as_mainfile(filepath=save_path, check_existing=False, compress=True)
            log("saved", save_path)
        except Exception as e:
            log("save failed", e)
    log("total %.1fs" % (time.time() - t0))
    return LOG


if __name__ == "__main__":
    build_all()
