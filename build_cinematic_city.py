def mat_metal(name, col=(0.44, 0.45, 0.46), rough=0.42, metal=1.0, rust=0.25, scale=1.0,
              streak=1.0, dent=0.5):
    """Painted or galvanised sheet metal that has been on a roof for thirty years."""
    m, g, out = new_mat(name)
    pos = obj_pos(g, -1800, 0)
    r_big = g.noise(g.mapping(pos, scale=(0.8 * scale, 0.8 * scale, 0.8 * scale), x=-1600, y=-100),
                    scale=3.0, detail=7.0, rough=0.62, x=-1420, y=-100)
    r_fine = g.noise(g.mapping(pos, scale=(9.0 * scale, 9.0 * scale, 9.0 * scale), x=-1600, y=-320),
                     scale=5.0, detail=6.0, rough=0.7, x=-1420, y=-320)
    # rust starts on the edges and runs down from them
    ew = edge_wear(g, 1.0, x=-1600, y=-560)
    run = g.noise(g.mapping(pos, scale=(4.0 * scale, 4.0 * scale, 0.22 * scale), x=-1600, y=-760),
                  scale=3.0, detail=6.0, rough=0.65, x=-1420, y=-760)
    rmask = g.math('ADD', g.math('MULTIPLY', g.fac(r_big), 0.75, x=-1240, y=-100),
                   g.math('MULTIPLY', ew, 0.55, x=-1240, y=-560), x=-1080, y=-300)
    rmask = g.math('MULTIPLY', rmask, g.mrange(g.fac(run), 0.28, 0.72, 0.25, 1.0, x=-1240, y=-760),
                   x=-920, y=-400)
    rmask = g.mrange(rmask, 0.38, 0.86, 0.0, 1.0, x=-760, y=-400)
    rmask = g.math('MULTIPLY', rmask, rust * streak, clamp=True, x=-600, y=-400)
    rust_col = g.mix(g.fac(r_fine), (0.155, 0.055, 0.020), (0.30, 0.115, 0.045),
                     dtype='RGBA', x=-760, y=-200)
    base = g.mix(0.25, col, g.fac(r_fine), dtype='RGBA', blend='OVERLAY', x=-600, y=0)
    base = g.mix(rmask, base, rust_col, dtype='RGBA', x=-300, y=-60)
    mtl = g.math('MULTIPLY', metal, g.math('SUBTRACT', 1.0, rmask, x=-300, y=-260), x=-140, y=-240)
    rgh = g.mix(rmask, g.mrange(g.fac(r_fine), 0.0, 1.0, rough - 0.10, rough + 0.14, x=-300, y=-420),
                0.92, dtype='FLOAT', x=-140, y=-400)
    hgt = g.math('ADD', g.math('MULTIPLY', g.fac(r_big), dent, x=-300, y=200),
                 g.math('MULTIPLY', rmask, 0.5, x=-300, y=120), x=-140, y=180)
    nm = g.bump(hgt, strength=0.35, distance=0.01, x=300, y=120)
    bsdf = g.principled(1300, 0, base=base, metal=mtl, rough=rgh, normal=nm)
    return finish(m, g, out, bsdf)


