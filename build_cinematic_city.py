def build_blade_sign(c, axis, sgn, plane, a_c, z_top, h, w, rng):
    """A projecting neon blade sign like the yellow one in the reference.

    Modelled hanging below the origin and projecting along local -Y, out of the wall.
    """
    rz, nrm = face_frame(axis, sgn)
    bm = bmesh.new()
    pj = 2.6
    mslot(bm, 0, slab, -w / 2, w / 2, -pj, -0.18, -h, 0.0)
    for (b0, b1) in ((-h - 0.14, -h), (0.0, 0.14)):
        mslot(bm, 1, slab, -w / 2 - 0.12, w / 2 + 0.12, -pj - 0.10, -0.10, b0, b1)
    mslot(bm, 1, slab, -w / 2 - 0.12, -w / 2, -pj - 0.10, -0.10, -h, 0.0)
    mslot(bm, 1, slab, w / 2, w / 2 + 0.12, -pj - 0.10, -0.10, -h, 0.0)
    mslot(bm, 1, obox, (0, -0.2, -0.1), (0, -pj, -h * 0.18), (1, 0, 0), 0.09, 0.09)
    mslot(bm, 1, obox, (0, -0.2, -h + 0.1), (0, -pj, -h * 0.82), (1, 0, 0), 0.09, 0.09)
    # neon tube outline round the outer edge of the blade
    for sx in (-1, 1):
        mslot(bm, 2, bm_cyl, (sx * (w / 2 - 0.14), -pj - 0.02, -h / 2), 0.05, h * 0.92, segs=8)
    for zz in (-0.16, -h + 0.16):
        mslot(bm, 2, bm_cyl, (0, -pj - 0.02, zz), 0.05, w * 0.9, rot=(0, radians(90), 0), segs=8)
    ob = bm_to_obj("BladeSign", bm, c, [MATS["sign_blade"], MATS["paint_dark"], MATS["neon"]])
    ob.rotation_euler = (0.0, 0.0, rz)
    base = Vector((plane, a_c, z_top)) if axis == 'x' else Vector((a_c, plane, z_top))
    ob.location = base + nrm * 0.05
    return ob


def camera_facing_sides(spec, cam_loc):
    """The facades of this building that are turned toward the camera."""
    out = []
    cx, cy = cam_loc.x, cam_loc.y
    if cx < spec["x0"]:
        out.append(('x', -1))
    if cx > spec["x1"]:
        out.append(('x', 1))
    if cy < spec["y0"]:
        out.append(('y', -1))
    if cy > spec["y1"]:
        out.append(('y', 1))
    return out


def build_signage(specs, c, rng):
    """Hang billboards on the buildings the camera is looking at."""
    if not P["signage"]:
        return 0
    cam = OBJS["camera"]
    cloc = cam.matrix_world.translation
    ads = [(("BROADWAY", 0.16, 0.9), ("24 HOURS", -0.34, 0.34)),
           (("CITY LIGHTS", 0.18, 0.8), ("DOWNTOWN", -0.32, 0.30)),
           (("TRIPLE CHEESE", 0.20, 0.62), ("EAT IN 24H", -0.30, 0.28)),
           (("NEW YORK", 0.16, 1.0),),
           (("THE DAILY", 0.18, 0.78), ("LATE EDITION", -0.30, 0.26)),
           (("METRO", 0.14, 1.0),)]
    pal = [((0.62, 0.055, 0.045), (0.85, 0.80, 0.72), (0.90, 0.72, 0.09)),
           ((0.045, 0.30, 0.16), (0.88, 0.86, 0.80), (0.80, 0.16, 0.10)),
           ((0.06, 0.13, 0.42), (0.86, 0.84, 0.78), (0.92, 0.60, 0.06)),
           ((0.80, 0.78, 0.72), (0.10, 0.10, 0.11), (0.72, 0.10, 0.09)),
           ((0.55, 0.13, 0.36), (0.88, 0.85, 0.78), (0.15, 0.55, 0.62))]
    n = 0
    cands = [s for s in specs if s.get("vis") and s.get("detail") and 40.0 < s["dist"] < 420.0]
    cands.sort(key=lambda s: s["dist"])
    for spec in cands:
        if n >= 9:
            break
        sides = [sd for sd in camera_facing_sides(spec, cloc)
                 if visible_box(spec["x0"], spec["x1"], spec["y0"], spec["y1"],
                                spec["h"] * 0.45, spec["h"] + 9.0, margin=0.02)]
        if not sides or rng.random() < 0.18:
            continue
        axis, sgn = rng.choice(sides)
        plane, (a0, a1) = side_plane((spec["x0"], spec["x1"], spec["y0"], spec["y1"]), axis, sgn)
        width = a1 - a0
        if width < 11.0:
            continue
        rooftop = rng.random() < 0.45
        w = min(width * 0.82, rng.uniform(13.0, 21.0))
        h = w * rng.uniform(0.34, 0.48)
        a_c = lerp(a0 + w / 2 + 0.4, a1 - w / 2 - 0.4, rng.random())
        z_c = (spec["h"] + 1.6 + h / 2 + 1.2) if rooftop else \
              lerp(spec["h"] * 0.55, spec["h"] - h * 0.7, rng.random())
        idx = n % len(ads)
        mat = mat_get("bill%d" % idx, mat_billboard, "Bill%d" % idx, pal[idx % len(pal)],
                      rng.uniform(1.6, 4.0), idx % 3)
        build_billboard(c, "Billboard%d" % n, axis, sgn, plane, a_c, z_c, w, h, mat, rng,
                        words=ads[idx], rooftop=rooftop)
        n += 1
        # a projecting blade sign lower down the same wall now and then
        if not rooftop and rng.random() < 0.5 and spec["h"] > 26.0:
            bh = rng.uniform(7.0, 12.0)
            ba = lerp(a0 + 2.0, a1 - 2.0, rng.random())
            build_blade_sign(c, axis, sgn, plane, ba, rng.uniform(16.0, spec["h"] * 0.5),
                             bh, rng.uniform(2.2, 3.0), rng)
    log("signage: %d billboards" % n)
    return n


