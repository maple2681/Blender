def mat_brick(name="Brick", col=(0.30, 0.13, 0.085), mortar=(0.52, 0.49, 0.44),
              bw=0.235, bh=0.082, joint=0.014):
    """Running-bond brick: per-brick colour, raked mortar joints, soot and rain streaks."""
    m, g, out = new_mat(name)
    uv, pz, nrm = wall_uv(g)
    u, v, _ = g.separate(uv, -1500, 300)
    row = g.math('FLOOR', g.math('DIVIDE', v, bh, x=-1360, y=260), x=-1240, y=260)
    # every other course is offset half a brick
    off = g.math('MULTIPLY', g.math('MODULO', row, 2.0, x=-1120, y=200), bw * 0.5, x=-1000, y=200)
    us = g.math('ADD', u, off, x=-880, y=300)
    cu = g.math('DIVIDE', us, bw, x=-760, y=300)
    cv = g.math('DIVIDE', v, bh, x=-760, y=180)
    fu, fv = g.math('FLOOR', cu, x=-640, y=300), g.math('FLOOR', cv, x=-640, y=180)
    lu, lv = g.math('FRACT', cu, x=-640, y=380), g.math('FRACT', cv, x=-640, y=100)
    # joint mask: 1 inside the brick, 0 in the mortar
    jw_u, jw_v = joint / bw * 0.5, joint / bh * 0.5
    mu = g.mrange(g.math('MINIMUM', lu, g.math('SUBTRACT', 1.0, lu, x=-500, y=340), x=-380, y=340),
                  0.0, jw_u, 0.0, 1.0, x=-260, y=340)
    mv = g.mrange(g.math('MINIMUM', lv, g.math('SUBTRACT', 1.0, lv, x=-500, y=140), x=-380, y=140),
                  0.0, jw_v, 0.0, 1.0, x=-260, y=140)
    brick = g.math('MULTIPLY', mu, mv, x=-120, y=250)                       # 1 = brick face
    # per-brick colour scatter
    wn = g.new('ShaderNodeTexWhiteNoise', -400, -60, noise_dimensions='3D')
    g.feed(g.i(wn, "Vector"), g.combine(fu, fv, obj_random(g, -560, -220), -520, -60))
    r = g.o(wn, "Value")
    shade = g.mrange(r, 0.0, 1.0, 0.62, 1.42, x=-240, y=-60)
    hue = g.mrange(r, 0.0, 1.0, -0.035, 0.045, x=-240, y=-160)
    bc = g.new('ShaderNodeHueSaturation', -60, -110)
    g.feed(g.i(bc, "Color"), col)
    g.feed(g.i(bc, "Hue"), g.math('ADD', 0.5, hue, x=-200, y=-260))
    g.feed(g.i(bc, "Saturation"), g.mrange(r, 0.0, 1.0, 0.75, 1.25, x=-240, y=-340))
    g.feed(g.i(bc, "Value"), shade)
    # surface noise inside each brick + mortar grain
    grain = g.noise(g.mapping(uv, scale=(90.0, 90.0, 1.0), x=-400, y=-460), scale=4.0, detail=6.0,
                    rough=0.7, x=-240, y=-460)
    face = g.mix(0.22, g.o(bc, "Color"), g.fac(grain), dtype='RGBA', blend='MULTIPLY', x=100, y=-110)
    base = g.mix(brick, mortar, face, dtype='RGBA', x=280, y=100)
    # dirt
    d = grime(g, uv, pz, scale=1.0, x=-900, y=-700)
    dirty = g.mix(g.math('MULTIPLY', d, 0.72, x=440, y=-120), base, (0.055, 0.05, 0.047),
                  dtype='RGBA', x=580, y=40)
    rough = g.mix(brick, 0.93, g.mrange(g.fac(grain), 0.0, 1.0, 0.60, 0.82, x=440, y=-300),
                  dtype='FLOAT', x=600, y=-260)
    rough = g.mix(d, rough, 0.95, dtype='FLOAT', x=740, y=-260)
    hgt = g.math('ADD', g.math('MULTIPLY', brick, 0.85, x=440, y=-440),
                 g.math('MULTIPLY', g.fac(grain), 0.15, x=440, y=-520), x=580, y=-460)
    nm = g.bump(hgt, strength=0.62, distance=0.012, x=900, y=-400)
    bsdf = g.principled(1300, 0, base=dirty, rough=rough, spec=0.32, normal=nm)
    return finish(m, g, out, bsdf)


def mat_stone(name="Stone", col=(0.40, 0.375, 0.335), panel=(1.35, 0.95), joint=0.02, soot=0.85):
    """Cut limestone / cast-stone cladding: panel joints, block scatter, soot in the joints."""
    m, g, out = new_mat(name)
    uv, pz, nrm = wall_uv(g)
    u, v, _ = g.separate(uv, -1500, 300)
    cu = g.math('DIVIDE', u, panel[0], x=-1340, y=320)
