def proto(name, bm, mats, c, smooth=False):
    ob = bm_to_obj("proto_" + name, bm, c, mats, smooth=smooth)
    ob.hide_render = True
    ob.hide_viewport = True
    return ob


def place(src, c, loc, rot=0.0, scale=1.0, name=None):
    """A linked copy of a prototype: same mesh data, so Cycles treats it as an instance."""
    ob = src.copy()
    ob.data = src.data
    ob.name = "CC_" + (name or src.name[9:])
    ob.hide_render = False
    ob.hide_viewport = False
    ob.location = loc
    ob.rotation_euler = (0.0, 0.0, rot)
    s = scale if isinstance(scale, (tuple, list)) else (scale, scale, scale)
    ob.scale = s
    c.objects.link(ob)
    return ob


def proto_water_tank(c, r=1.95, body=4.3, legs=3.4, seg=22):
    """The cedar tank on its steel frame that sits on every older New York roof."""
    bm = bmesh.new()
    z0 = legs
    mslot(bm, 0, bm_lathe, [(r, z0), (r, z0 + body)], seg=seg)
    mslot(bm, 0, bm_lathe, [(r * 1.03, z0 + body), (r * 0.56, z0 + body + 0.55),
                            (0.09, z0 + body + 0.82)], seg=seg, cap_top=True)   # shallow cone
    mslot(bm, 0, bm_lathe, [(r, z0), (r * 0.99, z0 - 0.12)], seg=seg, cap_bottom=True)
    for f in (0.18, 0.46, 0.74, 0.95):                       # steel hoops
        mslot(bm, 1, bm_torus, (0, 0, z0 + body * f), r + 0.035, 0.045, seg=seg, rseg=6)
    nleg = 6
    for i in range(nleg):                                     # splayed legs and cross bracing
        a = 2 * pi * i / nleg + 0.22
        p0 = Vector((cos(a) * (r + 0.55), sin(a) * (r + 0.55), 0.0))
        p1 = Vector((cos(a) * (r - 0.18), sin(a) * (r - 0.18), z0 + 0.1))
        mslot(bm, 1, obox, p0, p1, (0, 0, 1), 0.13, 0.13)
        b = 2 * pi * (i + 1) / nleg + 0.22
        q0 = Vector((cos(b) * (r + 0.55), sin(b) * (r + 0.55), 0.0))
        q1 = Vector((cos(b) * (r - 0.18), sin(b) * (r - 0.18), z0 + 0.1))
        mslot(bm, 1, obox, p0 + (p1 - p0) * 0.55, q0 + (q1 - q0) * 0.12, (0, 0, 1), 0.06, 0.06)
        mslot(bm, 1, obox, q0 + (q1 - q0) * 0.55, p0 + (p1 - p0) * 0.12, (0, 0, 1), 0.06, 0.06)
    for zz in (z0 * 0.42, z0 * 0.88):                         # ring beams
        mslot(bm, 1, bm_torus, (0, 0, zz), r + 0.32 - 0.36 * (zz / max(0.1, z0)), 0.055,
              seg=nleg * 3, rseg=5)
    # ladder up one side
    lx = r + 0.30
    for s in (-0.22, 0.22):
        mslot(bm, 1, obox, (lx, s, 0.2), (lx, s, z0 + body + 0.35), (1, 0, 0), 0.05, 0.05)
    k = 0.0
    while k < z0 + body + 0.4:
        mslot(bm, 1, obox, (lx, -0.22, k), (lx, 0.22, k), (0, 0, 1), 0.035, 0.035)
        k += 0.33
    mslot(bm, 1, bm_cyl, (0.0, 0.0, z0 + body + 1.05), 0.075, 0.5, segs=8)   # vent pipe
    return proto("tank", bm, [MATS["tankwood"], MATS["galv"]], c)


def proto_ac_unit(c, w=2.4, d=1.7, h=1.25, fans=1, louvre=True):
    """Packaged rooftop air handler: ribbed casing, access panel, fan cowl and curb."""
    bm = bmesh.new()
    mslot(bm, 0, slab, -w / 2, w / 2, -d / 2, d / 2, 0.16, 0.16 + h)
    mslot(bm, 1, slab, -w / 2 - 0.08, w / 2 + 0.08, -d / 2 - 0.08, d / 2 + 0.08, 0.0, 0.18)
    if louvre:
        n = max(3, int(h / 0.16))
        for i in range(n):
            z = 0.28 + i * (h - 0.28) / n
            mslot(bm, 1, slab, -w / 2 - 0.02, -w / 2 + 0.30, -d / 2 + 0.12, d / 2 - 0.12,
                  z, z + 0.055)
            mslot(bm, 1, slab, w / 2 - 0.30, w / 2 + 0.02, -d / 2 + 0.12, d / 2 - 0.12,
                  z, z + 0.055)
    mslot(bm, 1, slab, -w / 2 + 0.18, w / 2 - 0.18, d / 2 - 0.02, d / 2 + 0.03,
          0.32, 0.32 + h * 0.62)                                   # access panel
    for i in range(fans):
        cx = lerp(-w / 2 + w / (2 * fans), w / 2 - w / (2 * fans), i / max(1, fans - 1)) if fans > 1 else 0.0
        rr = min(0.55, w / (2.4 * fans))
        mslot(bm, 1, bm_lathe, [(rr + 0.10, 0.16 + h), (rr + 0.10, 0.16 + h + 0.22),
                                (rr + 0.16, 0.16 + h + 0.30)], seg=18)
        for k in range(4):                                          # fan blades and hub
            a = pi * k / 4
            mslot(bm, 1, bm_box, (cx, 0.0, 0.16 + h + 0.20), (rr * 1.75, 0.10, 0.02), (0.22, 0, a))
        mslot(bm, 1, bm_cyl, (cx, 0.0, 0.16 + h + 0.22), 0.09, 0.14, segs=10)
        for k in range(6):                                          # guard bars
            a = pi * k / 6
            mslot(bm, 1, obox, (cx - rr * cos(a), -rr * sin(a), 0.16 + h + 0.30),
                  (cx + rr * cos(a), rr * sin(a), 0.16 + h + 0.30), (0, 0, 1), 0.02, 0.02)
    mslot(bm, 1, bm_cyl, (-w / 2 + 0.25, -d / 2 - 0.18, 0.55), 0.085, 0.8, rot=(pi / 2, 0, 0), segs=8)
    return proto("ac%d" % int(w * 10), bm, [MATS["paint_grey"], MATS["galv"]], c)


def proto_condenser(c, n=4, w=1.15):
    """A bank of condenser fans on a steel skid."""
    bm = bmesh.new()
    L = n * w
    mslot(bm, 1, slab, -L / 2, L / 2, -w / 2 - 0.1, w / 2 + 0.1, 0.0, 0.14)
    for i in range(n):
        cx = -L / 2 + (i + 0.5) * w
        mslot(bm, 0, slab, cx - w * 0.46, cx + w * 0.46, -w / 2, w / 2, 0.14, 0.86)
        mslot(bm, 1, bm_lathe, [(w * 0.40, 0.86), (w * 0.40, 0.98), (w * 0.44, 1.02)], seg=16)
        for k in range(5):
            a = 2 * pi * k / 5
            mslot(bm, 1, bm_box, (cx, 0.0, 0.94), (w * 0.62, 0.09, 0.018), (0.28, 0, a))
        mslot(bm, 1, bm_cyl, (cx, 0.0, 0.96), 0.07, 0.10, segs=8)
        for k in range(5):
            a = pi * k / 5
            mslot(bm, 1, obox, (cx - w * 0.40 * cos(a), -w * 0.40 * sin(a), 1.02),
                  (cx + w * 0.40 * cos(a), w * 0.40 * sin(a), 1.02), (0, 0, 1), 0.016, 0.016)
    return proto("cond%d" % n, bm, [MATS["paint_grey"], MATS["galv"]], c)


def proto_vent(c, kind=0):
    """Vent stacks: mushroom cap, gooseneck, or a plain flue."""
    bm = bmesh.new()
    if kind == 0:
        mslot(bm, 0, bm_cyl, (0, 0, 0.6), 0.22, 1.2, segs=14)
        mslot(bm, 0, bm_lathe, [(0.40, 1.16), (0.42, 1.28), (0.16, 1.40)], seg=16)
        mslot(bm, 0, bm_cyl, (0, 0, 0.06), 0.30, 0.12, segs=14)
    elif kind == 1:
        pts = [(0, 0, 0.05), (0, 0, 1.25), (0, 0.16, 1.55), (0, 0.52, 1.60), (0, 0.72, 1.40)]
        mslot(bm, 0, bm_tube, pts, 0.17, seg=10)
        mslot(bm, 0, bm_cyl, (0, 0, 0.06), 0.26, 0.12, segs=12)
    else:
        mslot(bm, 0, bm_cyl, (0, 0, 1.0), 0.15, 2.0, segs=12)
        mslot(bm, 0, bm_torus, (0, 0, 1.95), 0.19, 0.035, seg=12, rseg=5)
        mslot(bm, 0, bm_cyl, (0, 0, 0.05), 0.24, 0.10, segs=12)
    return proto("vent%d" % kind, bm, [MATS["galv"]], c)


