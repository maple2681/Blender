def build_city():
    """Everything with a footprint: the buildings, their roofs and what stands on them."""
    rng = random.Random(P["seed"] * 13 + 5)
    c_b = coll("10_Buildings")
    c_r = coll("11_Rooftops")
    c_p = coll("90_Prototypes")
    specs = city_layout()
    if P["hero"]:
        specs.insert(0, hero_spec())
    for spec in specs:
        build_building(spec, specs, c_b, random.Random(spec["seed"]))
    log("buildings: %d objects" % len(specs))
    protos = build_roof_protos(c_p)
    n = 0
    for spec in specs:
        if spec.get("clutter"):
            n += dress_roof(spec, c_r, random.Random(spec["seed"] ^ 0x5bf03), protos)
    log("rooftop props: %d" % n)
    # fire escapes on the masonry buildings the camera can see
    if P["fire_escapes"]:
        cloc = OBJS["camera"].matrix_world.translation
        k = 0
        for spec in specs:
            if k >= 10 or not spec.get("detail") or spec["style"] not in ('brick', 'stone'):
                continue
            if spec["h"] < 18.0 or spec["dist"] > 240.0:
                continue
            sides = camera_facing_sides(spec, cloc)
            if not sides or rng.random() < 0.45:
                continue
            build_fire_escape(c_r, spec, *rng.choice(sides), rng=rng)
            k += 1
        log("fire escapes: %d" % k)
    # scaffolding against one visible facade, and a tower crane over the rooftops
    if P["scaffolding"]:
        for spec in specs:
            if spec.get("detail") and spec["style"] in ('brick', 'stone') \
                    and 20.0 < spec["h"] < 55.0 and spec["y0"] > 0.0 and spec["dist"] < 260.0:
                build_scaffold(c_r, spec["x0"] + 1.0, spec["x1"] - 1.0, spec["y0"] - 1.1,
                               0.2, min(spec["h"], 34.0), rng, face=-1.0)
                break
    if P["rooftop_crane"]:
        best = None
        for spec in specs:
            if not spec.get("clutter") or not spec.get("roofs"):
                continue
            rect, zd, zt = spec["roofs"][-1]
            if spec["x1"] < P["avenue_x"] and 25.0 < spec["h"] < 90.0 and spec["dist"] < 330.0:
                if best is None or spec["h"] > best[0]["h"]:
                    best = (spec, rect, zd)
        if best:
            spec, rect, zd = best
            build_crane(c_r, 0.5 * (rect[0] + rect[1]), 0.5 * (rect[2] + rect[3]), zd,
                        h=rng.uniform(28.0, 40.0), jib=rng.uniform(22.0, 30.0),
                        rot=rng.uniform(-0.6, 0.6))
            log("crane on the roof at z=%.0f" % zd)
    return specs


