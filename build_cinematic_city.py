def setup_world():
    """Physical sky, warmed and slightly dimmed, with the sun disc left to the sun lamp."""
    w = bpy.data.worlds.get("CC_World") or bpy.data.worlds.new("CC_World")
    SC.world = w
    setp(w, "use_nodes", True)
    nt = w.node_tree
    for n in list(nt.nodes):
        nt.nodes.remove(n)
    g = NT(nt)
    out = g.new('ShaderNodeOutputWorld', 1000, 0)
    sky = g.new('ShaderNodeTexSky', -700, 0)
    for st in ('MULTIPLE_SCATTERING', 'NISHITA', 'HOSEK_WILKIE'):   # 5.x renamed Nishita
        if setp(sky, "sky_type", st):
            break
    setp(sky, "sun_elevation", radians(P["sun_elevation"]))
    setp(sky, "sun_rotation", radians(P["sun_azimuth"]))
    setp(sky, "sun_disc", False)              # the sun lamp does the disc, with a clean shadow
    setp(sky, "sun_intensity", 1.0)
    setp(sky, "air_density", P["air_density"])
    setp(sky, "dust_density", P["aerosol_density"])
    setp(sky, "ozone_density", P["ozone_density"])
    setp(sky, "altitude", 120.0)
    tint = g.new('ShaderNodeHueSaturation', -380, 0)
    g.feed(g.i(tint, "Color"), g.o(sky))
    g.feed(g.i(tint, "Saturation"), 1.06)
    g.feed(g.i(tint, "Value"), P["sky_strength"])
    bg = g.new('ShaderNodeBackground', 500, 0)
    g.feed(g.i(bg, "Color"), g.o(tint, "Color"))
    g.feed(g.i(bg, "Strength"), 1.0)
    g.link(bg, out.inputs["Surface"])
    OBJS["sky_node"] = sky
    # let Cycles importance-sample the bright sky near the sun
    setp(w.cycles, "sampling_method", 'AUTOMATIC')
    return w


def sun_direction():
    el, az = radians(P["sun_elevation"]), radians(P["sun_azimuth"])
    return Vector((sin(az) * cos(el), cos(az) * cos(el), sin(el)))


def build_sun(c):
    """The sun lamp: low, warm and slightly softened, aimed down the canyon."""
    d = bpy.data.lights.new("CC_Sun", 'SUN')
    d.energy = P["sun_strength"]
    d.color = P["sun_tint"]
    d.angle = radians(P["sun_angle"])
    setp(d.cycles, "cast_shadow", True)
    sun = link_obj("Sun", d, c)
    v = sun_direction()
    sun.location = v * 900.0 + Vector((0.0, 180.0, 0.0))
    sun.rotation_euler = (-v).to_track_quat('-Z', 'Y').to_euler()
    OBJS["sun"] = sun
    if P["bounce_light"]:
        # the buildings behind the camera are culled away, so their warm bounce is faked here
        ld = bpy.data.lights.new("CC_Bounce", 'AREA')
        ld.shape = 'RECTANGLE'
        ld.size, ld.size_y = 260.0, 220.0
        ld.energy = 55000.0
