def geo(g, x=-2000, y=0):
    return g.new('ShaderNodeNewGeometry', x, y)


def obj_pos(g, x=-2000, y=-160):
    """Object-space position.

    Props are instanced and some of them move, so their textures must be tied to the object
    rather than to the world: world coordinates make a tank's staves smear into a gradient
    and make the dust on a moving car swim through the paint.
    """
    tc = g.new('ShaderNodeTexCoord', x, y)
    return g.o(tc, "Object")


def obj_random(g, x=-2000, y=-300):
    n = g.new('ShaderNodeObjectInfo', x, y)
    return g.o(n, "Random")


def wall_uv(g, scale=1.0, x=-1800, y=0):
    """Horizontal-along-the-wall / vertical coordinates for a box-shaped building.

    Walls facing X read their horizontal coordinate from world Y and vice versa, so brick
    courses and window grids run round all four faces without a UV map.
    """
    gn = geo(g, x - 250, y)
    px, py, pz = g.separate(g.o(gn, "Position"), x - 120, y + 120)
    nx, ny, nz = g.separate(g.o(gn, "Normal"), x - 120, y - 140)
    ax = g.math('ABSOLUTE', nx, x=x, y=y - 120)
    ay = g.math('ABSOLUTE', ny, x=x, y=y - 200)
    facing_x = g.math('GREATER_THAN', ax, ay, x=x + 140, y=y - 160)     # 1 on the X-facing walls
    h = g.mix(facing_x, px, py, dtype='FLOAT', x=x + 300, y=y)
    # flip the horizontal axis on the far side so the pattern never mirrors into a seam
    return g.combine(g.math('MULTIPLY', h, scale, x=x + 440, y=y + 60),
                     g.math('MULTIPLY', pz, scale, x=x + 440, y=y - 60), 0.0, x + 580, y), pz, g.o(gn, "Normal")


def cell_hash(g, uv, cw, ch, seed=0.0, x=-1000, y=0):
    """Snap wall coordinates to a window grid; returns (random per cell, u in cell, v in cell)."""
    u, v, _ = g.separate(uv, x - 200, y)
    cu = g.math('DIVIDE', u, cw, x=x - 60, y=y + 120)
    cv = g.math('DIVIDE', v, ch, x=x - 60, y=y - 120)
    fu = g.math('FLOOR', cu, x=x + 80, y=y + 120)
    fv = g.math('FLOOR', cv, x=x + 80, y=y - 120)
    wn = g.new('ShaderNodeTexWhiteNoise', x + 240, y, noise_dimensions='4D')
    g.feed(g.i(wn, "Vector"), g.combine(fu, fv, obj_random(g, x + 60, y - 320), x + 160, y - 200))
    g.feed(g.i(wn, "W"), seed)
    rnd = g.o(wn, "Value")
    lu = g.math('FRACT', cu, x=x + 240, y=y + 220)
    lv = g.math('FRACT', cv, x=x + 240, y=y + 140)
    return rnd, lu, lv


def grime(g, uv, pz, scale=1.0, streak=1.0, x=-900, y=-600):
    """Soot in the texture, vertical rain streaks below the ledges, dirt low on the wall."""
    st = g.noise(g.mapping(uv, scale=(6.0 * scale, 0.09 * scale, 1.0), x=x - 300, y=y),
                 scale=3.0, detail=5.0, rough=0.62, x=x - 120, y=y)
    blot = g.noise(g.mapping(uv, scale=(0.35 * scale, 0.35 * scale, 1.0), x=x - 300, y=y - 220),
                   scale=2.2, detail=6.0, rough=0.55, x=x - 120, y=y - 220)
    d = g.mix(0.55, g.fac(blot), g.fac(st), dtype='FLOAT', blend='MULTIPLY', x=x + 80, y=y - 100)
    d = g.mrange(d, 0.18, 0.62, 0.0, 1.0, x=x + 220, y=y - 100)
    d = g.math('MULTIPLY', d, streak, x=x + 360, y=y - 100)
    return d


def edge_wear(g, strength=1.0, x=-900, y=-1000):
    """Pointiness-driven bright wear on the corners and dark in the recesses."""
    gn = geo(g, x - 200, y)
    p = g.o(gn, "Pointiness")
    return g.mrange(p, 0.42, 0.62, 0.0, strength, x=x, y=y)


