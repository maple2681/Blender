def build_crane(c, x, y, z, h=34.0, jib=26.0, rot=0.0):
    """A tower crane over the rooftops, like the one in the reference."""
    bm = bmesh.new()
    r = 1.05
    legs = [(-r, -r), (r, -r), (r, r), (-r, r)]
    for (lx, ly) in legs:
        mslot(bm, 0, obox, (lx, ly, 0.0), (lx, ly, h), (0, 0, 1), 0.10, 0.10)
    n = int(h / 1.7)
    for i in range(n):
        z0, z1 = i * h / n, (i + 1) * h / n
        for k in range(4):
            a, b = legs[k], legs[(k + 1) % 4]
            mslot(bm, 0, obox, (a[0], a[1], z1), (b[0], b[1], z1), (0, 0, 1), 0.05, 0.05)
            mslot(bm, 0, obox, (a[0], a[1], z0), (b[0], b[1], z1), (0, 0, 1), 0.042, 0.042)
    # slewing ring, cab and the jib
    mslot(bm, 1, slab, -1.3, 1.3, -1.3, 1.3, h, h + 0.5)
    mslot(bm, 1, slab, -1.0, 0.6, -1.25, -0.2, h + 0.5, h + 2.6)
    ztop = h + 0.6
    for side in (-0.55, 0.55):
        mslot(bm, 0, obox, (0.0, side, ztop), (jib, side, ztop), (0, 0, 1), 0.10, 0.10)
        mslot(bm, 0, obox, (0.0, side, ztop + 1.25), (jib * 0.94, side, ztop + 0.75), (0, 0, 1),
              0.07, 0.07)
        mslot(bm, 0, obox, (0.0, side, ztop), (-jib * 0.36, side, ztop), (0, 0, 1), 0.09, 0.09)
    k = 0.0
    while k < jib:
        mslot(bm, 0, obox, (k, -0.55, ztop), (k, 0.55, ztop), (0, 0, 1), 0.045, 0.045)
        mslot(bm, 0, obox, (k, -0.55, ztop), (min(jib, k + 1.6), -0.55, ztop + 1.1),
              (0, 0, 1), 0.035, 0.035)
        mslot(bm, 0, obox, (k, 0.55, ztop), (min(jib, k + 1.6), 0.55, ztop + 1.1),
              (0, 0, 1), 0.035, 0.035)
        k += 1.6
    mslot(bm, 0, obox, (0, 0, ztop + 0.2), (0, 0, ztop + 7.0), (1, 0, 0), 0.30, 0.30)  # A-frame
    mslot(bm, 0, obox, (0, 0, ztop + 7.0), (jib * 0.62, 0, ztop + 0.9), (0, 0, 1), 0.045, 0.045)
    mslot(bm, 0, obox, (0, 0, ztop + 7.0), (-jib * 0.34, 0, ztop + 0.3), (0, 0, 1), 0.045, 0.045)
    mslot(bm, 1, slab, -jib * 0.36, -jib * 0.20, -0.7, 0.7, ztop - 0.9, ztop - 0.1)    # counterweight
    # trolley and hook block on its rope
    tx = jib * 0.55
    mslot(bm, 1, slab, tx - 0.4, tx + 0.4, -0.5, 0.5, ztop - 0.45, ztop - 0.05)
    mslot(bm, 0, obox, (tx, 0, ztop - 0.45), (tx, 0, ztop - 13.5), (1, 0, 0), 0.028, 0.028)
    mslot(bm, 1, slab, tx - 0.28, tx + 0.28, -0.22, 0.22, ztop - 14.3, ztop - 13.5)
    ob = bm_to_obj("Crane", bm, c, [MATS["crane_paint"], MATS["paint_grey"]])
    ob.location = (x, y, z)
    ob.rotation_euler = (0, 0, rot)
    return ob


def build_scaffold(c, x0, x1, y, z0, z1, rng, face=1.0):
    """Tube-and-board scaffolding standing against a facade."""
    bm = bmesh.new()
    d = 1.05
    lifts = max(2, int((z1 - z0) / 2.05))
    bays = max(1, int((x1 - x0) / 2.4))
    for i in range(bays + 1):
        xx = lerp(x0, x1, i / bays)
        for yy in (0.0, d * face):
            mslot(bm, 0, obox, (xx, yy, 0.0), (xx, yy, z1 - z0), (1, 0, 0), 0.055, 0.055)
        for k in range(lifts + 1):
            zz = (z1 - z0) * k / lifts
            mslot(bm, 0, obox, (xx, 0.0, zz), (xx, d * face, zz), (0, 0, 1), 0.05, 0.05)
    for k in range(lifts + 1):
        zz = (z1 - z0) * k / lifts
        for yy in (0.0, d * face):
            mslot(bm, 0, obox, (x0, yy, zz), (x1, yy, zz), (0, 0, 1), 0.05, 0.05)
        if k > 0:                                            # boards on every lift
            mslot(bm, 1, slab, x0, x1, min(0.06, d * face), max(0.06, d * face * 0.95),
                  zz - 0.05, zz)
            mslot(bm, 0, obox, (x0, 0.0, zz), (x1, d * face, zz - (z1 - z0) / lifts),
                  (0, 0, 1), 0.04, 0.04)
            mslot(bm, 0, obox, (x0, d * face, zz - 0.9), (x1, d * face, zz - 0.9),
                  (0, 0, 1), 0.04, 0.04)
    ob = bm_to_obj("Scaffold", bm, c, [MATS["galv"], MATS["board"]])
    ob.location = (0.0, y, z0)
    return ob


def build_fire_escape(c, spec, axis, sgn, rng):
    """Zig-zag fire escape bolted to a masonry facade: platforms, stairs, railings, drop ladder."""
    rect = (spec["x0"], spec["x1"], spec["y0"], spec["y1"])
    plane, (a0, a1) = side_plane(rect, axis, sgn)
    w = min(3.4, (a1 - a0) * 0.42)
    a_world = lerp(a0 + w, a1 - w, rng.random())   # where along the facade it hangs
    ac = 0.0                                       # built centred in its own local frame
    depth = 1.25
    fh = 3.4
    n = max(2, min(7, int((spec["h"] - 5.0) / fh)))
    bm = bmesh.new()

    def B(p0, p1, up, ww, tt, slot=0):
        mslot(bm, slot, obox, p0, p1, up, ww, tt)

    for i in range(n):
        z = 5.0 + i * fh
        # platform grating and its two support brackets
        mslot(bm, 1, slab, ac - w / 2, ac + w / 2, 0.0, depth, z, z + 0.06)
        for aa in (ac - w / 2 + 0.1, ac + w / 2 - 0.1):
            B((aa, 0.0, z), (aa, depth, z), (0, 0, 1), 0.05, 0.05)
            B((aa, depth, z), (aa, 0.02, z - 0.75), (0, 0, 1), 0.04, 0.04)
        # railing
        for aa in (ac - w / 2, ac + w / 2):
            B((aa, depth, z), (aa, depth, z + 1.05), (1, 0, 0), 0.035, 0.035)
        B((ac - w / 2, depth, z + 1.05), (ac + w / 2, depth, z + 1.05), (0, 0, 1), 0.035, 0.035)
        B((ac - w / 2, depth, z + 0.55), (ac + w / 2, depth, z + 0.55), (0, 0, 1), 0.025, 0.025)
        k = ac - w / 2
        while k < ac + w / 2:
            B((k, depth, z), (k, depth, z + 1.05), (1, 0, 0), 0.016, 0.016)
            k += 0.17
        for aa in (ac - w / 2, ac + w / 2):                  # returns along the sides
            B((aa, 0.0, z + 1.05), (aa, depth, z + 1.05), (0, 0, 1), 0.03, 0.03)
            B((aa, 0.0, z), (aa, 0.0, z + 1.05), (1, 0, 0), 0.03, 0.03)
        # stair flight up to the next platform, alternating side to side
        if i < n - 1:
            s = 1.0 if i % 2 == 0 else -1.0
            xa, xb = ac + s * (w / 2 - 0.55), ac - s * (w / 2 - 0.55)
            for off in (-0.42, 0.42):
                B((xa + off * 0.0, depth * 0.15, z + 0.06), (xb + off * 0.0, depth * 0.85, z + fh),
                  (0, 0, 1), 0.05, 0.05)
            for t in range(9):
                u = (t + 0.5) / 9.0
                mslot(bm, 1, slab, lerp(xa, xb, u) - 0.42, lerp(xa, xb, u) + 0.42,
                      lerp(depth * 0.15, depth * 0.85, u) - 0.12,
                      lerp(depth * 0.15, depth * 0.85, u) + 0.12,
                      lerp(z + 0.06, z + fh, u), lerp(z + 0.06, z + fh, u) + 0.04)
            B((xa, depth * 0.15, z + 1.0), (xb, depth * 0.85, z + fh + 1.0), (0, 0, 1), 0.03, 0.03)
    # counterweighted drop ladder to the street
    for aa in (ac - 0.42, ac + 0.42):
        B((aa, depth * 0.7, 5.0), (aa, depth * 0.7, 1.9), (1, 0, 0), 0.035, 0.035)
    k = 2.1
    while k < 5.0:
        B((ac - 0.42, depth * 0.7, k), (ac + 0.42, depth * 0.7, k), (0, 0, 1), 0.025, 0.025)
        k += 0.32
    ob = bm_to_obj("FireEscape", bm, c, [MATS["escape_iron"], MATS["escape_grate"]])
    # local +Y is "out of the wall", local X runs along it; rotate that onto the chosen facade
    if axis == 'x':
        ob.location = (plane, a_world, 0.0)
        ob.rotation_euler = (0.0, 0.0, radians(-90.0) if sgn > 0 else radians(90.0))
    else:
        ob.location = (a_world, plane, 0.0)
        ob.rotation_euler = (0.0, 0.0, 0.0 if sgn > 0 else radians(180.0))
    return ob


