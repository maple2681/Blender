"""
Builds a dense Manhattan-style downtown seen from a helicopter, fully procedural:
no external texture files, no asset libraries - every building, rooftop tank,
taxi and billboard is generated by this script.

  * a real street grid: one wide avenue running away from the camera, cross streets,
    named blocks subdivided into lots, and a facade generator that gives every lot a
    different building - glass curtain-wall towers, brick pre-war mid-rises, stone
    Art Deco slabs with setbacks, and low cluttered infill
  * a hero curtain-wall tower filling the left of frame: floor slabs, mullions,
    spandrel panels and dirty glass that reflects the sky and the buildings opposite
  * the New York rooftop: timber water tanks on steel legs, packaged HVAC units with
    fan cowls, condenser banks, duct runs, vent stacks, bulkheads, skylights, parapets
    with coping, antenna masts, dishes, pigeon spikes, scaffolding and a tower crane
  * the street: asphalt with patches, cracks, tar seams, manholes and painted lane
    markings, zebra crossings, kerbs and flagstone sidewalks, lamp standards, traffic
    signals, hydrants, planters and street trees
  * traffic that drives: yellow cabs, sedans, vans, box trucks and a bus, each on a lane
    with its own speed, stopping at the signal and pulling away again, headlights and
    brake lights that come on in shadow
  * lit signage: procedurally painted billboards, a projecting blade sign and shop
    fascias, packed into the .blend as generated images
  * late-afternoon light: physical sky with the sun low in the west, so the canyon floor
    is in shadow and only the upper storeys and roofs catch the warm light; city haze
    turns the gaps between buildings into god rays
  * steam: plumes rolling off the roof vents and drifting out of the street manholes
  * a slow 12 s helicopter move with a gentle descent, handheld float and rack focus
  * Cycles settings, AgX colour management, compositor grade, 24 fps / 288 frames

Run: Blender > Scripting workspace > open this file > Run Script
     or from a terminal:  blender --python build_cinematic_city.py
Re-running is safe: everything it creates is prefixed "CC_" and rebuilt in a scene
called "Cinematic_City" (other scenes - the 5AM and 3AM ones - are left alone).
Written for Blender 5.x (tested on 5.0).
"""

