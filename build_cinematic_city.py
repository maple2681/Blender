def build_camera():
    """A slow helicopter drift down the avenue with a gentle descent and a handheld float."""
    c = coll("00_Camera")
    cs = Vector(P["cam_start"])
    rig = new_empty("CamRig", c, cs, 3.0, 'ARROWS')
    cd = bpy.data.cameras.new("CC_Camera")
    cd.lens = P["lens"]
    cd.sensor_fit = 'HORIZONTAL'
    cd.sensor_width = P["sensor"]
    cd.clip_start = 0.5
    cd.clip_end = 6000.0
    cam = link_obj("Camera", cd, c, rig)
    cd.dof.use_dof = True
    cd.dof.focus_distance = P["focus_dist"]
    cd.dof.aperture_fstop = P["fstop"]
    cd.dof.aperture_blades = 8
    fs, fe = P["frame_start"], P["frame_end"]
    y0, y1 = P["cam_yaw"]
    p0, p1 = P["cam_pitch"]
    ce = cs + heading_vec(0.5 * (y0 + y1)) * P["cam_travel"] + Vector((0.0, 0.0, P["cam_rise"]))
    for (f, loc, yaw, pitch) in ((fs, cs, y0, p0), (fe, ce, y1, p1)):
        rig.location = loc
        rig.rotation_euler = Euler((radians(90.0 + pitch), radians(P["cam_roll"]),
                                    radians(-yaw)), 'XYZ')
        rig.keyframe_insert("location", frame=f)
        rig.keyframe_insert("rotation_euler", frame=f)
    ease_keys(rig, fs, fe, 0.55)
    if P["cam_drift"]:
        # a slow handheld float on the camera itself, never repeating
        for idx, (strength, scale, phase) in enumerate(((0.0016, 190.0, 3.0),
                                                        (0.0011, 240.0, 17.0),
                                                        (0.0021, 210.0, 41.0))):
            cam.keyframe_insert("rotation_euler", index=idx, frame=fs)
            fcu = _find_fcurve(cam, "rotation_euler", idx)
            if fcu is not None:
                mod = fcu.modifiers.new('NOISE')
                mod.strength = strength
                mod.scale = scale
                mod.phase = phase
                setp(mod, "depth", 1)
        for idx, strength in ((0, 0.10), (2, 0.14)):
            cam.keyframe_insert("location", index=idx, frame=fs)
            fcu = _find_fcurve(cam, "location", idx)
            if fcu is not None:
                mod = fcu.modifiers.new('NOISE')
                mod.strength = strength
                mod.scale = 205.0
                mod.phase = 7.0 + idx * 13.0
    SC.camera = cam
    OBJS["camera"] = cam
    OBJS["cam_rig"] = rig
    SC.frame_set(fs)
    OBJS["cam_mats"] = cam_matrices(5)
    return cam


