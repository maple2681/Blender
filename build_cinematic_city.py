def prepare_scene():
    """Remove everything a previous run created, then (re)use scene 'Cinematic_City'."""
    global SC, RNG
    RNG = random.Random(P["seed"])
    pre = ("CC_",)
    for ob in list(bpy.data.objects):
        if ob.name.startswith(pre):
            bpy.data.objects.remove(ob, do_unlink=True)
    for c in list(bpy.data.collections):
        if c.name.startswith(pre):
            bpy.data.collections.remove(c)
    for _ in range(3):
        for store in (bpy.data.meshes, bpy.data.curves, bpy.data.lights, bpy.data.cameras,
                      bpy.data.materials, bpy.data.node_groups, bpy.data.worlds, bpy.data.images,
                      bpy.data.particles, bpy.data.textures, bpy.data.actions):
            for d in list(store):
                if d.name.startswith(pre) and d.users == 0:
                    store.remove(d)
    sc = bpy.data.scenes.get("Cinematic_City")
    if sc is None:
        sc = bpy.data.scenes.new("Cinematic_City")
    SC = sc
    try:
        if bpy.context.window is not None:
            bpy.context.window.scene = sc
    except Exception as e:
        log("window scene", e)
    MATS.clear()
    OBJS.clear()
    GROUPS.clear()
    IMGS.clear()
    return sc


def coll(name, parent=None):
    full = "CC_" + name
    c = bpy.data.collections.get(full)
    if c is None:
        c = bpy.data.collections.new(full)
        (parent or SC.collection).children.link(c)
    return c


def link_obj(name, data, c, parent=None):
    ob = bpy.data.objects.new("CC_" + name, data)
    c.objects.link(ob)
    if parent is not None:
        ob.parent = parent
    return ob


