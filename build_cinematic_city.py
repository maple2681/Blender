def mat_steam(name="Steam", density=1.0, emission=0.0):
    """A plume of vapour: narrow at the vent, widening and dissolving as it climbs and drifts."""
    m, g, out = new_mat(name)
    pos = g.o(g.new('ShaderNodeNewGeometry', -1700, 200), "Position")
    t = time_value(g, -1700, 420, 1.0)
    # the turbulence rises and drifts downwind, so the plume keeps changing shape
    drift = g.vmath('ADD', pos, g.combine(g.math('MULTIPLY', t, 0.75, x=-1480, y=460),
                                          g.math('MULTIPLY', t, -0.55, x=-1480, y=380),
                                          g.math('MULTIPLY', t, -1.25, x=-1480, y=300),
                                          -1320, 400), x=-1140, y=320)
    n1 = g.noise(g.mapping(drift, scale=(0.42, 0.42, 0.24), x=-960, y=420), scale=2.4, detail=9.0,
                 rough=0.60, x=-780, y=420)
    n2 = g.noise(g.mapping(drift, scale=(1.6, 1.6, 0.85), x=-960, y=200), scale=3.4, detail=8.0,
                 rough=0.64, x=-780, y=200)
    turb = g.mix(0.45, g.fac(n1), g.fac(n2), dtype='FLOAT', x=-560, y=320)
    turb = g.mrange(turb, 0.40, 0.88, 0.0, 1.0, x=-380, y=320)
    # --- the envelope, in the domain's own 0..1 box ------------------------
    gen = g.o(g.new('ShaderNodeTexCoord', -1700, -300), "Generated")
    u, v, w = g.separate(gen, -1500, -300)
    rr = g.vmath('DISTANCE', g.combine(u, v, 0.5, -1320, -240), (0.5, 0.5, 0.5), x=-1140, y=-240)
    radius = g.mrange(w, 0.0, 1.0, 0.055, 0.40, x=-1320, y=-420)      # widens as it rises
    shape = g.mrange(g.math('DIVIDE', rr, radius, x=-960, y=-300), 0.35, 1.0, 1.0, 0.0,
                     x=-780, y=-300)
    foot = g.mrange(w, 0.0, 0.05, 0.0, 1.0, x=-960, y=-520)           # starts at the vent
    top = g.mrange(w, 0.42, 1.0, 1.0, 0.0, x=-960, y=-640)            # frays out at the top
    fade = g.math('MULTIPLY', g.math('MULTIPLY', shape, foot, x=-560, y=-400),
                  top, x=-380, y=-460)
    dens = g.math('MULTIPLY', g.math('MULTIPLY', turb, fade, x=-160, y=0),
                  density * 1.15, x=40, y=0)
    sc = g.new('ShaderNodeVolumeScatter', 1100, 0)
    g.feed(g.i(sc, "Color"), (0.90, 0.91, 0.93))
    g.feed(g.i(sc, "Density"), dens)
    g.feed(g.i(sc, "Anisotropy"), 0.30)
    set_volume_opts(m)
    return finish(m, g, out, volume=sc)


