# ============================================================================
#  TRAFFIC  -  a little car-following simulation, then baked to keyframes
# ============================================================================
def signal_green(t, phase=0.0):
    """True when this direction has a green light."""
    return (t / P["signal_period"] + phase) % 1.0 < P["signal_green"]


def simulate(vehicles, dt, nsteps, phase=0.0, record=False):
    """Free speed, a headway to the car in front, and a stop at the red light."""
    lanes = {}
    for v in vehicles:
        lanes.setdefault(v["lane"], []).append(v)
    hist = [[] for _ in vehicles] if record else None
    a_acc, a_brk = 2.3, 4.8
    for step in range(nsteps):
        green = signal_green(step * dt, phase)
        for group in lanes.values():
            group.sort(key=lambda v: v["s"])
            n = len(group)
            for i, v in enumerate(group):
                des = v["vmax"]
                if n > 1:
                    lead = group[(i + 1) % n]
                    gap = lead["s"] - v["s"] - v["len"]
                    if gap < 0.0:
                        gap += v["loop"]                       # the leader is round the loop
                    des = min(des, max(0.0, (gap - 1.7) / 0.85))
                if not green:
                    u = v["s"] % v["loop"]
                    for sl in v["stops"]:
                        d = (sl - u) % v["loop"]
                        if d < 90.0:
                            des = min(des, (2.0 * a_brk * max(0.0, d - 4.5)) ** 0.5)
                            break
                if des > v["v"]:
                    v["v"] = min(des, v["v"] + a_acc * dt)
                else:
                    v["v"] = max(0.0, max(des, v["v"] - a_brk * dt))
                v["brake"] = 1.0 if v["v"] < v["vmax"] * 0.88 else 0.0
                v["s"] += v["v"] * dt
        if record:
            for i, v in enumerate(vehicles):
                hist[i].append((v["s"], v["brake"]))
    return hist


def lane_pos(v, s):
    """Travel coordinate -> world position for a vehicle's lane."""
    u = s % v["loop"]
    if v["axis"] == 'y':
        y = v["lo"] + u if v["dir"] > 0 else v["hi"] - u
        return (v["cross"], y, 0.0)
    x = v["lo"] + u if v["dir"] > 0 else v["hi"] - u
    return (x, v["cross"], 0.0)


def build_traffic(c, rng, protos):
    """Fill the avenue and one cross street with vehicles that queue at the lights."""
    if not P["traffic"]:
        return []
    L = {nm: ln for (nm, k, ln, w, col) in VEHICLES}
    kinds = (["cab"] * 7 + ["cab2"] * 5 + ["sedan_w", "sedan_k", "sedan_r", "sedan_b"] * 3
             + ["suv", "suv", "van", "truck", "bus"])
    half = P["avenue_road"] * 0.5
    bar = P["cross_road"] * 0.5 + 4.6                      # stop bar set back from the junction
    # --- the avenue -----------------------------------------------------
    y_lo, y_hi = P["cross_streets"][0] - 45.0, 480.0
    loop_y = y_hi - y_lo
    av = []
    lanes_y = [(off, d) for off in (2.4, 5.9, 9.4) for d in (1, -1)]
    per = max(1, P["n_vehicles"] // len(lanes_y))
    for (off, d) in lanes_y:
        stops = sorted(((cy - bar) - y_lo if d > 0 else y_hi - (cy + bar)) % loop_y
                       for cy in P["cross_streets"] if y_lo < cy < y_hi)
        for k in range(per):
            kind = rng.choice(kinds)
            av.append(dict(lane="Y%+.1f%+d" % (off, d), kind=kind, len=L[kind], loop=loop_y,
                           axis='y', dir=d, lo=y_lo, hi=y_hi, cross=P["avenue_x"] + d * off,
                           s=k * (loop_y / per) + rng.uniform(-4.0, 4.0),
                           v=P["traffic_speed"] * 0.9,
                           vmax=P["traffic_speed"] * rng.uniform(0.82, 1.16),
                           brake=0.0, stops=stops))
    # --- one cross street, on the opposite phase -------------------------
    cy = P["cross_streets"][1]
    x_lo, x_hi = -175.0, 175.0
    loop_x = x_hi - x_lo
    cr = []
    for off in (2.3, 5.8):
        for d in (1, -1):
            stop = ((P["avenue_x"] - half - 4.6) - x_lo if d > 0
                    else x_hi - (P["avenue_x"] + half + 4.6)) % loop_x
            for k in range(4):
                kind = rng.choice(kinds)
                cr.append(dict(lane="X%+.1f%+d" % (off, d), kind=kind, len=L[kind], loop=loop_x,
                               axis='x', dir=d, lo=x_lo, hi=x_hi, cross=cy - d * off,
                               s=k * (loop_x / 4) + rng.uniform(-8.0, 8.0),
                               v=P["traffic_speed"] * 0.8,
                               vmax=P["traffic_speed"] * rng.uniform(0.75, 1.02),
                               brake=0.0, stops=[stop]))
    dt = 1.0 / P["fps"]
    nst = P["frame_end"] - P["frame_start"] + 1
    ph = P["signal_green"]                                  # the cross street gets the other phase
    simulate(av, dt, int(10.0 * P["fps"]))                  # settle the queues before frame 1
    simulate(cr, dt, int(10.0 * P["fps"]), phase=ph)
    hist_a = simulate(av, dt, nst, record=True)
    hist_c = simulate(cr, dt, nst, phase=ph, record=True)
    out = []
    step = 2
    for group, hist in ((av, hist_a), (cr, hist_c)):
        for v, h in zip(group, hist):
            if v["axis"] == 'y':
                rot = radians(90.0) if v["dir"] > 0 else radians(-90.0)
            else:
                rot = 0.0 if v["dir"] > 0 else radians(180.0)
            ob = place(protos[v["kind"]], c, lane_pos(v, h[0][0]), rot,
                       name="veh%03d_%s" % (len(out), v["kind"]))
            for f in range(P["frame_start"], P["frame_end"] + 1, step):
                s, brake = h[min(len(h) - 1, f - P["frame_start"])]
                ob.location = lane_pos(v, s)
                ob.keyframe_insert("location", frame=f)
                ob.color = (brake, 1.0, 1.0, 1.0)
                ob.keyframe_insert("color", frame=f)
            ad = ob.animation_data
            if ad and ad.action:
                for fc in _fcurves(ad.action):
                    for kp in fc.keyframe_points:
                        kp.interpolation = 'LINEAR' if fc.data_path == "location" else 'CONSTANT'
            out.append(ob)
    log("traffic: %d vehicles on %d lanes" % (len(out), len(set(v["lane"] for v in av + cr))))
    return out


